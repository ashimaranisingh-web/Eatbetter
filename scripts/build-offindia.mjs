// Builds offindia.js: Open Food Facts products sold in India that have
// nutrition, for instant offline barcode lookups and packaged-food search.
//
//   node scripts/build-offindia.mjs            (streams the export, ~1.5 GB, nothing saved)
//   node scripts/build-offindia.mjs file.csv.gz (or a local copy)
//
// Source: Open Food Facts, https://world.openfoodfacts.org/data
// Licence: Open Database License (ODbL). Credit "Open Food Facts" in the app.
// Re-run monthly to pick up new products.
import fs from 'node:fs';
import https from 'node:https';
import zlib from 'node:zlib';
import readline from 'node:readline';

const SRC = process.argv[2] || 'https://static.openfoodfacts.org/data/en.openfoodfacts.org.products.csv.gz';

function open(src) {
  if (!/^https?:/.test(src)) return Promise.resolve(fs.createReadStream(src));
  return new Promise((ok, no) => {
    const get = url => https.get(url, { headers: { 'User-Agent': 'Menufi-data-build/1.0' } }, res => {
      if (res.statusCode >= 300 && res.statusCode < 400 && res.headers.location) return get(res.headers.location);
      if (res.statusCode !== 200) return no(new Error('HTTP ' + res.statusCode));
      ok(res);
    }).on('error', no);
    get(src);
  });
}

const num = v => { if (v === '' || v == null) return null; const n = +v; return Number.isFinite(n) ? n : null; };
const r1 = n => n == null ? null : Math.round(n * 10) / 10;
const clean = s => String(s || '').replace(/\s+/g, ' ').trim();

const stream = (await open(SRC)).pipe(zlib.createGunzip());
const rl = readline.createInterface({ input: stream, crlfDelay: Infinity });
let head = null, col = {}, seen = 0, kept = 0;
const out = new Map();

for await (const line of rl) {
  if (!head) {
    head = line.split('\t');
    head.forEach((h, i) => { col[h] = i; });
    for (const need of ['code', 'product_name', 'countries_tags', 'energy-kcal_100g']) if (!(need in col)) throw new Error('missing column ' + need);
    continue;
  }
  seen++;
  if (seen % 500000 === 0) console.error(`  …${seen.toLocaleString()} rows read, ${kept.toLocaleString()} kept`);
  const f = line.split('\t'), g = k => f[col[k]];
  if (!/en:india/.test(g('countries_tags') || '')) continue;
  const code = (g('code') || '').replace(/\D/g, '');
  if (code.length < 8 || code.length > 14) continue;
  let kcal = num(g('energy-kcal_100g'));
  if (kcal == null && num(g('energy_100g')) != null) kcal = num(g('energy_100g')) / 4.184;
  if (kcal == null || kcal < 0 || kcal > 950) continue;
  const name = clean(g('product_name')).slice(0, 80);
  if (!name) continue;
  const brand = clean((g('brands') || '').split(',')[0]).slice(0, 40);
  const qty = clean(g('quantity')).slice(0, 30);
  const cats = g('categories_tags') || '';
  const liquid = /\d\s*(ml|cl|l|ltr|fl\.? ?oz)\b/i.test(qty + ' ' + (g('serving_size') || '')) || /en:(beverages|drinks|waters|juices|sodas|milks)\b/.test(cats);
  let sodium = num(g('sodium_100g'));
  if (sodium == null && num(g('salt_100g')) != null) sodium = num(g('salt_100g')) / 2.5;
  out.set(code, [code, name, brand, Math.round(kcal), r1(num(g('proteins_100g'))), r1(num(g('carbohydrates_100g'))), r1(num(g('fat_100g'))),
    r1(num(g('fiber_100g'))), r1(num(g('sugars_100g'))), sodium == null ? null : Math.round(sodium * 1000),
    num(g('product_quantity')), num(g('serving_quantity')), qty, liquid ? 1 : 0]);
  kept = out.size;
}

const rows = [...out.values()];
const js = `// Generated by scripts/build-offindia.mjs on ${new Date().toISOString().slice(0, 10)}. Do not edit by hand.
// Open Food Facts products sold in India, with nutrition per 100 g (or 100 ml).
// Data © Open Food Facts contributors, Open Database License (ODbL).
// Row: [barcode, name, brand, kcal, protein, carbs, fat, fibre, sugar g, sodium mg, pack g/ml, serving g/ml, quantity text, drink 1/0]
window.EB_OFF_INDIA = ${JSON.stringify(rows).replace(/\],\[/g, '],\n[')};
`;
fs.writeFileSync(new URL('../offindia.js', import.meta.url), js);
console.log(`offindia.js: ${rows.length.toLocaleString()} products (from ${seen.toLocaleString()} rows), ${(js.length / 1048576).toFixed(2)} MB`);
